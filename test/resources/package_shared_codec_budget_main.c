/* Select a borrowed local identity policy without replacing initialized native ownership on failure. */
static void identity_policy_contract(const srl_buffer* xml, const srl_limits* limits) {
  const srl_xml_operation_codec* codec = srl_xml_operation_codec_identity_xml_registry();
  const size_t complete_owner_tuples = expected_native_references / 3u;
  for (size_t direction = 0; direction < 2u; ++direction) {
    for (size_t tight = 0; tight < 2u; ++tight) {
      identity_xml_registry model = {0};
      require(identity_xml_registry_decode_xml(&model, xml->data, xml->size, limits) == srl_ok, "local identity policy owner setup");
      const identity_xml_registry snapshot = model;
      srl_xml_identity_limits identity = srl_xml_default_identity_limits();
      identity.max_tuples = complete_owner_tuples - tight;
      const srl_xml_operation_policies policies = {NULL, NULL, NULL, &identity};
      ledger value = default_ledger(); srl_xml_operation operation = operation_for(&value); operation.policies = &policies;
      srl_buffer output = {0}; require(srl_reserve(&output, 1u), "local identity policy output sentinel");
      output.data[0] = 0xa5u; output.size = 1u; const srl_buffer previous_output = output;
      const srl_status status = direction ? codec->encode(&model, &output, limits, NULL, &operation) :
          codec->decode(&model, xml->data, xml->size, limits, NULL, &operation);
      require(status == (tight ? srl_limit : srl_ok), "exact and one-tight borrowed identity tuple policy");
      require(operation.policies == &policies && policies.identity == &identity && !operation.caller_status,
          "local identity policy borrows exact caller pointers without a caller failure");
      if (tight) {
        require(operation.failure == srl_xml_operation_resource_limit && operation.field && strstr(operation.field, "entries.label"),
            "identity-local tuple quota names the native unique member");
        require(!memcmp(&model, &snapshot, sizeof(model)), "rejected local identity policy retains initialized native owner");
        require(output.data == previous_output.data && output.size == previous_output.size && output.capacity == previous_output.capacity && output.data[0] == 0xa5u,
            "rejected local identity policy retains initialized output bytes");
      }
      identity_xml_registry_free(&model); srl_buffer_free(&output);
    }
  }
}

/* Preserve old aggregate layouts, function signatures, bytes and caller-owned error identity. */
static void native_contract(const srl_buffer* xml, const size_t expected_inventory[3]) {
  const srl_limits old_limits = {64u * 1024u * 1024u, 16u * 1024u * 1024u, 1000000u, 64u, srl_read_strict};
  srl_status (*old_decode)(identity_xml_registry*, const uint8_t*, size_t, const srl_limits*) = identity_xml_registry_decode_xml;
  srl_status (*old_encode)(const identity_xml_registry*, srl_buffer*, const srl_limits*) = identity_xml_registry_encode_xml;
  identity_xml_registry model = {0}; require(old_decode(&model, xml->data, xml->size, &old_limits) == srl_ok, "old positional limits and decode pointer");
  srl_buffer old_bytes = {0}, new_bytes = {0}; require(old_encode(&model, &old_bytes, &old_limits) == srl_ok, "old encode function pointer");
  ledger encoding = default_ledger(); srl_xml_operation operation = operation_for(&encoding);
  require(srl_xml_operation_codec_identity_xml_registry()->encode(&model, &new_bytes, &old_limits, NULL, &operation) == srl_ok, "operation-aware native encode");
  require(old_bytes.size == new_bytes.size && !memcmp(old_bytes.data, new_bytes.data, old_bytes.size), "unchanged old native XML bytes");
  require(encoding.used[srl_xml_operation_references] == 4, "encode counts repeated completed keyrefs");
  identity_xml_registry_free(&model); srl_buffer_free(&old_bytes); srl_buffer_free(&new_bytes);
  identity_policy_contract(xml, &old_limits);

  ledger measured = default_ledger(); operation = operation_for(&measured);
  require(decode_three(xml, &measured, &operation), "three caller-composed independent native owners");
  require(measured.used[srl_xml_operation_nodes] == expected_inventory[0] && measured.used[srl_xml_operation_attributes] == expected_inventory[1],
      "four elements and five physical attributes per owner counted once across identity reparsing");
  native_scalar_bytes = measured.used[srl_xml_operation_scalar_bytes];
  require(native_scalar_bytes == expected_inventory[2], "independent expanded names namespace vocabulary and decoded values admitted once");
  const srl_xml_operation_resource resources[] = {srl_xml_operation_references, srl_xml_operation_work, srl_xml_operation_allocation};
  for (size_t index = 0; index < sizeof(resources) / sizeof(resources[0]); ++index) {
    for (size_t tight = 0; tight < 2; ++tight) {
      ledger bounded = default_ledger(); bounded.maximum[resources[index]] = measured.used[resources[index]] - tight;
      operation = operation_for(&bounded);
      const bool accepted = decode_three(xml, &bounded, &operation);
      require(accepted == !tight, "exact and one-tight composed native ledger");
      if (tight) { require(operation.caller_status == caller_failure && operation.userdata == &bounded && bounded.field[0], "original caller status userdata and member context"); }
    }
  }
  ledger cancelled = default_ledger(); cancelled.failure = caller_failure; operation = operation_for(&cancelled);
  model = (identity_xml_registry){0};
  require(srl_xml_operation_codec_identity_xml_registry()->decode(&model, xml->data, xml->size, &old_limits, NULL, &operation) != srl_ok && operation.caller_status == caller_failure, "original arbitrary cancellation status");
  const size_t first_polls = cancelled.polls; cancelled.failure = 70001;
  require(srl_xml_operation_codec_identity_xml_registry()->decode(&model, xml->data, xml->size, &old_limits, NULL, &operation) != srl_ok && operation.caller_status == caller_failure && cancelled.polls == first_polls, "first operation failure remains sticky");
  identity_xml_registry_free(&model);
  ledger recovered = default_ledger(); operation = operation_for(&recovered);
  require(decode_three(xml, &recovered, &operation), "fresh context recovers after independent failure");
  ledger local = default_ledger(); operation = operation_for(&local);
  srl_limits local_limits = old_limits; local_limits.max_depth = 0;
  require(srl_xml_operation_codec_identity_xml_registry()->decode(&model, xml->data, xml->size, &local_limits, NULL, &operation) == srl_limit &&
      operation.failure == srl_xml_operation_resource_limit && operation.field && *operation.field && !operation.caller_status,
      "native-local depth quota retains explicit resource classification");
  identity_xml_registry_free(&model);

  thread_input inputs[] = {{xml, false, 0}, {xml, false, 0}};
#if defined(_WIN32)
  HANDLE threads[2];
  for (size_t index = 0; index < 2; ++index) { threads[index] = CreateThread(NULL, 0, concurrent_decode, &inputs[index], 0, NULL); require(threads[index] != NULL, "create independent context thread"); }
  require(WaitForMultipleObjects(2, threads, TRUE, INFINITE) == WAIT_OBJECT_0, "join independent contexts");
  for (size_t index = 0; index < 2; ++index) { require(CloseHandle(threads[index]) != 0, "close context thread"); }
#else
  pthread_t threads[2];
  for (size_t index = 0; index < 2; ++index) { require(!pthread_create(&threads[index], NULL, concurrent_decode, &inputs[index]), "create independent context thread"); }
  for (size_t index = 0; index < 2; ++index) { require(!pthread_join(threads[index], NULL), "join independent contexts"); }
#endif
  require(inputs[0].success && inputs[1].success && inputs[0].references == expected_native_references && inputs[1].references == expected_native_references, "concurrent contexts retain separate accounting");
}

