/** Encode the same portable absolute dependency paths emitted by Serializer. */
function escapeDependency(value) {
  return value.replaceAll('\\', '/').replaceAll('$', () => '$$').replace(/[ #:]/g, '\\$&');
}

/** Resolve navigation against a mutable filesystem containing no executable/build APIs. */
function fixture(entries, directories = [], headers) {
  const files = new Map(Object.entries(entries).map(([name, text]) => [file(name), text]));
  let cancelled = false;
  const host = { read: async name => files.get(name), cancelled: () => cancelled,
    files: async () => ({ schemas: [...files.keys()].filter(name => name.endsWith('.serializer')),
      sources: [...files.keys()].filter(name => /\.(hpp|h|hxx|hh|cpp|cc|cxx|ipp|inl)$/.test(name)),
      headers: headers ? headers.map(file) : [...files.keys()].filter(name => /\.(hpp|h|hxx)$/.test(name)) }),
    includeDirectories: directories.map(group => group.map(file)) };
  return { files, host, cancel: () => { cancelled = true; },
    resolver: () => new Navigator(host),
    at: (name, word, last = false) => last ? files.get(file(name)).lastIndexOf(word) : files.get(file(name)).indexOf(word) };
}

/** Keep location assertions focused on destination names and selected source spelling. */
function selected(state, targets) {
  return targets.map(target => [path.relative(root, target.file).replaceAll('\\', '/'),
    state.files.get(target.file).slice(target.start, target.end)]);
}

