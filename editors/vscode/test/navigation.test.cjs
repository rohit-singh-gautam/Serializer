test('language 1.22 cache modifiers preserve qualified and ordinary cache type navigation', async () => {
  const source = 'serializer version 1.22.0; include middle; namespace app { class model { ' +
    'public cache(priority = 200) lib::preview thumbnail; public cache lib::preview fallback; ' +
    'public cache map(string) lib::preview indexed; public cache variant(lib::preview = value, uint64 = number) selected; ' +
    'public lib::cache ordinary; } }';
  const common = 'serializer version 1.22.0; namespace lib { class preview {} class cache {} }';
  const state = fixture({ 'model.serializer': source, 'middle.serializer': 'include common;', 'common.serializer': common });
  const index = indexSource(source, true);
  assert.ok(!index.references.some(reference => reference.name === 'priority'));
  for (const name of ['lib::preview', 'lib::cache']) {
    let start = source.indexOf(name);
    while (start >= 0) {
      for (let cursor = start; cursor <= start + name.length; ++cursor) {
        for (const definition of [false, true]) {
          assert.deepEqual(selected(state, await state.resolver().schema(file('model.serializer'), cursor, definition)),
            [['common.serializer', name.split('::').at(-1)]]);
        }
      }
      start = source.indexOf(name, start + name.length);
    }
  }
  const legacy = indexSource('serializer version 1; class cache {} class model { public cache value; }', true);
  assert.ok(legacy.references.some(reference => reference.name === 'cache'));
  const live = source.replace('lib::preview thumbnail', 'lib::cache thumbnail');
  state.files.set(file('model.serializer'), live);
  assert.deepEqual(selected(state, await state.resolver().schema(file('model.serializer'), live.indexOf('lib::cache'), true)),
    [['common.serializer', 'cache']]);
});

