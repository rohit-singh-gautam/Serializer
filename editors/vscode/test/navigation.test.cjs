test('C++ include search respects target directories and ordinary-header shadowing', async () => {
  const state = fixture({ 'main.cpp': '#include <account.hpp>', 'account.serializer': 'serializer version 1; class account {}',
    'first/account.hpp': '// Ordinary unrelated header', 'second/account.hpp': banner + 'class account {};' }, [['first', 'second']]);
  assert.deepEqual(await state.resolver().cppInclude(file('main.cpp'), state.at('main.cpp', 'account'), true), []);
  state.files.delete(file('first/account.hpp'));
  assert.deepEqual(selected(state, await state.resolver().cppInclude(file('main.cpp'), state.at('main.cpp', 'account'), true)),
    [['second/account.hpp', '']]);
});

test('quoted local includes shadow generated outputs and comments/macros are ignored', async () => {
  const state = fixture({ 'main.cpp': '#include "account.hpp"', 'account.hpp': '// local header',
    'account.serializer': 'serializer version 1; class account {}', 'build/account.hpp': banner + 'class account {};' });
  assert.deepEqual(await state.resolver().cppInclude(file('main.cpp'), state.at('main.cpp', 'account'), false), []);
  for (const source of ['// #include <account.hpp>', '/*\n#include <account.hpp>\n*/', '#include HEADER',
    'auto text = R"code(\n#include <account.hpp>\n)code";']) {
    assert.equal(cppIncludeAt(source, source.indexOf('account')), undefined);
  }
  assert.equal(cppIncludeAt('#include <account.hpp> // account', 28), undefined);
});

test('dependency parser handles escaped paths and rejects stale target identities', () => {
  const header = file('generated #1$/account.hpp');
  const schema = file('schema #1$/account.serializer');
  const text = `${escapeDependency(header)}: \\\n ${escapeDependency(schema)}\n`;
  assert.deepEqual(dependencySchemas(text, header), [schema]);
  assert.deepEqual(dependencySchemas(text, file('other/account.hpp')), []);
});

test('deleted outputs and edits are reflected by the next request; cancellation yields no results', async () => {
  const state = fixture({ 'account.serializer': 'serializer version 1; class account {}',
    'build/account.hpp': banner + 'class account {};' });
  assert.equal((await state.resolver().headers(file('account.serializer'))).length, 1);
  state.files.delete(file('build/account.hpp'));
  assert.deepEqual(await state.resolver().headers(file('account.serializer')), []);
  state.files.set(file('account.serializer'), 'serializer version 1; class changed {}');
  assert.deepEqual(selected(state, await state.resolver().schema(file('account.serializer'), state.at('account.serializer', 'changed'), false)),
    [['account.serializer', 'changed']]);
  state.cancel();
  assert.deepEqual(await state.resolver().schema(file('account.serializer'), state.at('account.serializer', 'changed'), false), []);
});

