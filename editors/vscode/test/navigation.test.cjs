const assert = require('node:assert/strict');
const path = require('node:path');
const { test } = require('node:test');
const { Navigator } = require('../out/navigator');
const { indexSource, generatedNames, dependencySchemas, cppIncludeAt } = require('../out/navigation_model');

const root = path.resolve('navigation workspace');
const file = name => path.join(root, name);
const banner = '// Generated by Serializer. Do not edit this file manually.\n';

/** Encode the same portable absolute dependency paths emitted by Serializer. */
function escapeDependency(value) {
  return value.replaceAll('\\', '/').replaceAll('$', () => '$$').replace(/[ #:]/g, '\\$&');
}

/** Resolve navigation against a mutable filesystem containing no executable/build APIs. */
function fixture(entries, directories = [], headers) {
  const files = new Map(Object.entries(entries).map(([name, text]) => [file(name), text]));
  let cancelled = false;
  const host = { read: async name => files.get(name), cancelled: () => cancelled,
    files: async () => ({ schemas: [...files.keys()].filter(name => name.endsWith('.serializer')),
      headers: headers ? headers.map(file) : [...files.keys()].filter(name => /\.(hpp|h|hxx)$/.test(name)) }),
    includeDirectories: directories.map(group => group.map(file)) };
  return { files, host, cancel: () => { cancelled = true; },
    resolver: () => new Navigator(host),
    at: (name, word, last = false) => last ? files.get(file(name)).lastIndexOf(word) : files.get(file(name)).indexOf(word) };
}

/** Keep location assertions focused on destination names and selected source spelling. */
function selected(state, targets) {
  return targets.map(target => [path.relative(root, target.file).replaceAll('\\', '/'),
    state.files.get(target.file).slice(target.start, target.end)]);
}

test('schema includes and qualified class references navigate into source and merged output', async () => {
  const state = fixture({
    'request.serializer': 'serializer version 1; include types/account.serializer; namespace app { class request { public data::account owner; }}',
    'types/account.serializer': 'serializer version 1; namespace data { class account {} }',
    'build/request.hpp': banner + 'namespace data { class account {}; } namespace app { class request {}; }',
    'build/request.hpp.d': `${escapeDependency(file('build/request.hpp'))}: ${escapeDependency(file('request.serializer'))} ${escapeDependency(file('types/account.serializer'))}`
  });
  const resolver = state.resolver();
  assert.deepEqual(selected(state, await resolver.schema(file('request.serializer'), state.at('request.serializer', 'types/account'), false)),
    [['types/account.serializer', '']]);
  assert.deepEqual(selected(state, await resolver.schema(file('request.serializer'), state.at('request.serializer', 'types/account'), true)),
    [['build/request.hpp', '']]);
  assert.deepEqual(selected(state, await resolver.schema(file('request.serializer'), state.at('request.serializer', 'data::account'), false)),
    [['types/account.serializer', 'account']]);
  assert.deepEqual(selected(state, await resolver.schema(file('request.serializer'), state.at('request.serializer', 'data::account'), true)),
    [['build/request.hpp', 'account']]);
  assert.deepEqual(selected(state, await resolver.headers(file('types/account.serializer'))), [['build/request.hpp', '']]);
});

test('source navigation works before generation and missing output returns no destination', async () => {
  const state = fixture({ 'account.serializer': 'serializer version 1; class account {}',
    'main.cpp': '#include <account.hpp>\naccount value;' });
  const resolver = state.resolver();
  assert.deepEqual(selected(state, await resolver.cppInclude(file('main.cpp'), state.at('main.cpp', 'account'), false)),
    [['account.serializer', '']]);
  assert.deepEqual(await resolver.cppInclude(file('main.cpp'), state.at('main.cpp', 'account'), true), []);
  assert.deepEqual(await resolver.schema(file('account.serializer'), state.at('account.serializer', 'account'), true), []);
  assert.deepEqual(await resolver.headers(file('account.serializer')), []);
});

test('missing includes, comments, strings, field names and unresolved types yield no declaration', async () => {
  const source = 'serializer version 1; include missing.serializer; class account {} class request { public account account; public unknown other; public string label { "account" }; /* public account fake; */ }';
  const state = fixture({ 'request.serializer': source });
  for (const position of [source.indexOf('missing'), source.indexOf('account;'), source.indexOf('unknown'),
    source.indexOf('account"'), source.indexOf('account fake')]) {
    assert.deepEqual(await state.resolver().schema(file('request.serializer'), position, false), []);
  }
});

test('nearest namespaces, global qualifiers, inheritance and container type positions resolve', async () => {
  const source = 'serializer version 1; class account {} namespace a { class account {} namespace b { class request : public account { public array account list; public map(account) ::account lookup; public union(account = one, ::account = two) choice; } } }';
  const state = fixture({ 'request.serializer': source });
  for (const marker of ['account list', 'account)', 'account = one']) {
    const result = await state.resolver().schema(file('request.serializer'), source.indexOf(marker), false);
    assert.equal(result[0].start, source.indexOf('account {}', source.indexOf('namespace a')));
  }
  assert.equal((await state.resolver().schema(file('request.serializer'), source.indexOf(': public account') + ': public '.length, false))[0].start,
    source.indexOf('account {}', source.indexOf('namespace a')));
  for (const marker of ['::account lookup', '::account = two']) {
    const result = await state.resolver().schema(file('request.serializer'), source.indexOf(marker), false);
    assert.equal(result[0].start, source.indexOf('account'));
  }
});

