"""Regenerate frozen Unicode 17 XML pattern tables from official Unicode data files.

Download UnicodeData.txt and Blocks.txt from https://www.unicode.org/Public/17.0.0/ucd/,
Blocks-3.2.0.txt from https://www.unicode.org/Public/3.2-Update/, and Blocks-3.txt
from https://www.unicode.org/Public/3.0-Update/ into --data-directory. Historical
block spellings preserve the XSD 1.0 names. See LICENSE-UNICODE for data terms.
"""
import argparse
import hashlib
from pathlib import Path


def main():
    """Emit immutable category ranges and block aliases; no target SDK needs Unicode providers."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data-directory', required=True, type=Path)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'src/xml_pattern_unicode.inc')
    args = parser.parse_args()
    sources = {name: (args.data_directory / name).read_bytes() for name in
               ('UnicodeData.txt', 'Blocks.txt', 'Blocks-3.2.0.txt', 'Blocks-3.txt')}
    categories = ['Cn'] * 0x110000
    first = None
    for line in sources['UnicodeData.txt'].decode().splitlines():
        code, name, category, *_ = line.split(';')
        code = int(code, 16)
        if name.endswith(', First>'):
            first = code
        elif name.endswith(', Last>'):
            assert first is not None
            categories[first:code + 1] = [category] * (code + 1 - first)
            first = None
        else:
            categories[code] = category
    assert first is None
    lines = ['// Generated by qualification/generate_xml_unicode_tables.py; do not edit.',
             '// Unicode 17.0.0 data, Copyright Unicode, Inc.; see LICENSE-UNICODE.',
             '// SPDX-License-Identifier: Unicode-3.0']
    for name, source in sources.items():
        lines.append('// ' + name + ' SHA-256 ' + hashlib.sha256(source).hexdigest())
    lines += ['struct unicode_category_range { std::uint32_t first, last; std::string_view category; };',
              'constexpr unicode_category_range unicode_category_ranges[]{']
    start = 0
    for code in range(1, len(categories) + 1):
        if code == len(categories) or categories[code] != categories[start]:
            lines.append(f'  {{0x{start:x}U, 0x{code - 1:x}U, "{categories[start]}"}},')
            start = code
    lines += ['};', 'struct unicode_block_range { std::string_view name; std::uint32_t first, last; };',
              'constexpr unicode_block_range unicode_block_ranges[]{']
    blocks = {}
    for filename in ('Blocks-3.txt', 'Blocks-3.2.0.txt', 'Blocks.txt'):
        for line in sources[filename].decode().splitlines():
            line = line.split('#')[0].strip()
            if not line:
                continue
            if filename == 'Blocks-3.txt':
                low, high, name = map(str.strip, line.split(';'))
            else:
                extent, name = map(str.strip, line.split(';'))
                low, high = extent.split('..')
            blocks[name.replace(' ', '')] = (int(low, 16), int(high, 16))
    for name, (low, high) in sorted(blocks.items()):
        lines.append(f'  {{"{name}", 0x{low:x}U, 0x{high:x}U}},')
    lines += ['};', '']
    args.output.write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    main()
