// Own one atomically reserved sibling directory until publication transfers its contents.
class staging_directory {
  std::filesystem::path path_{};

public:
  // Reserve a unique location in the destination's filesystem so rename can publish atomically.
  explicit staging_directory(const std::filesystem::path& destination) {
    constexpr unsigned maximum_attempts{64U};
    const auto tick = std::chrono::steady_clock::now().time_since_epoch().count();
    for (unsigned attempt{}; attempt < maximum_attempts; ++attempt) {
      const auto candidate =
          destination.parent_path() /
          (".serializer-xsd-" + std::to_string(tick) + '-' + std::to_string(attempt));
      if (std::filesystem::create_directory(candidate)) {
        path_ = candidate;
        return;
      }
    }
    throw std::runtime_error{"Cannot reserve XSD bundle staging directory"};
  }
  // Remove only the directory this instance reserved; cleanup must not replace the original error.
  ~staging_directory() {
    std::error_code ignored{};
    std::filesystem::remove_all(path_, ignored);
  }
  // A reserved directory has one cleanup owner.
  staging_directory(const staging_directory&) = delete;
  // Do not transfer cleanup obligations implicitly.
  staging_directory& operator=(const staging_directory&) = delete;
  // Borrow the reserved location until this owner is destroyed.
  [[nodiscard]] const std::filesystem::path& path() const noexcept {
    return path_;
  }
};

// Admit only the exporter's portable flat XSD filenames into the published inventory.
inline std::string checked_filename(const std::filesystem::path& path) {
  const auto name = path.generic_string();
  if (name.empty() || path.has_parent_path() || path.is_absolute() || path.has_root_name() ||
      path.extension() != ".xsd" ||
      name.find_first_not_of("abcdefghijklmnopqrstuvwxyz0123456789_.-") != std::string::npos ||
      name == ".xsd") {
    throw std::invalid_argument{"XSD export requires portable relative schema filenames"};
  }
  return name;
}

// Write one complete staged file and detect delayed write/close failures before publication.
inline void write(const std::filesystem::path& path, std::string_view bytes) {
  std::ofstream output{};
  output.exceptions(std::ios::failbit | std::ios::badbit);
  output.open(path, std::ios::binary | std::ios::trunc);
  output.write(bytes.data(), static_cast<std::streamsize>(bytes.size()));
  output.close();
}

// Require an existing reviewed bundle to match every generated byte and contain no extra files.
inline bool identical(const std::filesystem::path& directory,
                      const std::map<std::string, std::string>& files) {
  std::size_t count{};
  for (const auto& entry : std::filesystem::directory_iterator(directory)) {
    if (entry.is_symlink() || !entry.is_regular_file()) {
      return false;
    }
    const auto found = files.find(entry.path().filename().generic_string());
    if (found == files.end() || entry.file_size() != found->second.size()) {
      return false;
    }
    std::ifstream input{entry.path(), std::ios::binary};
    // Read the expected extent only, even if a concurrently changed file grows after file_size.
    std::string bytes(found->second.size(), '\0');
    input.read(bytes.data(), static_cast<std::streamsize>(bytes.size()));
    if (input.gcount() != static_cast<std::streamsize>(bytes.size()) ||
        input.peek() != std::char_traits<char>::eof() || input.bad() || bytes != found->second) {
      return false;
    }
    ++count;
  }
  return count == files.size();
}
