// Publish a checked complete XSD bundle once; identical reruns succeed without overwriting edits.
// The parent must exist. Existing differing paths remain untouched, including on validation failure.
// Callers must serialize mutations to the same output directory during publication.
inline void publish_xsd_bundle(const schema_bundle& bundle, const std::filesystem::path& output) {
  if (bundle.documents.empty() || bundle.identity.size() != 64U ||
      bundle.identity.find_first_not_of("0123456789abcdef") != std::string::npos) {
    throw std::invalid_argument{"XSD export requires a complete pinned bundle"};
  }
  const auto destination = std::filesystem::absolute(output).lexically_normal();
  if (destination.filename().empty() || !std::filesystem::is_directory(destination.parent_path()) ||
      std::filesystem::is_symlink(std::filesystem::symlink_status(destination))) {
    throw std::invalid_argument{
        "XSD bundle output requires a real directory parent and a new directory name"};
  }
  std::map<std::string, std::string> files{};
  std::string manifest{"{\n  \"version\": 1,\n  \"entry\": \""};
  const auto entry = bundle_output_detail::checked_filename(bundle.documents.front().path);
  manifest += entry + "\",\n  \"sha256\": \"" + bundle.identity + "\",\n  \"schemas\": [";
  for (const auto& document : bundle.documents) {
    const auto name = bundle_output_detail::checked_filename(document.path);
    if (!files.emplace(name, document.bytes).second) {
      throw std::invalid_argument{"Duplicate exported XSD filename"};
    }
    if (files.size() > 1U) {
      manifest += ',';
    }
    manifest += "\n    \"" + name + '"';
  }
  manifest += "\n  ]\n}\n";
  files.emplace("manifest.json", std::move(manifest));
  if (std::filesystem::exists(destination)) {
    if (std::filesystem::is_directory(destination) &&
        bundle_output_detail::identical(destination, files)) {
      return;
    }
    throw std::invalid_argument{
        "XSD bundle output differs; export to a new directory and review the changes"};
  }
  bundle_output_detail::staging_directory staging{destination};
  for (const auto& [name, bytes] : files) {
    bundle_output_detail::write(staging.path() / name, bytes);
  }
  const auto checked = read_schema_bundle(staging.path() / entry, false);
  if (checked->identity != bundle.identity) {
    throw std::invalid_argument{
        "Exported XSD bundle identity does not match its local dependency inventory"};
  }
  std::filesystem::rename(staging.path(), destination);
}
